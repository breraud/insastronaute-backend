ALTER TABLE departments ADD COLUMN color VARCHAR(7) NOT NULL DEFAULT '#6366F1';

UPDATE departments SET color = CASE UPPER(short_name)
    WHEN 'GM' THEN '#3B82F6'
    WHEN 'ITI' THEN '#06B6D4'
    WHEN 'MECA' THEN '#EAB308'
    WHEN 'EP' THEN '#EC4899'
    WHEN 'CFI' THEN '#EF4444'
    WHEN 'MRIE' THEN '#22C55E'
    WHEN 'GC' THEN '#F97316'
    ELSE '#6366F1'
END;
