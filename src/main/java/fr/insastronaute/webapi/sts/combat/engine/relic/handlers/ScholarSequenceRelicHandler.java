package fr.insastronaute.webapi.sts.combat.engine.relic.handlers;

import fr.insastronaute.webapi.sts.combat.catalog.CardDefinition;
import fr.insastronaute.webapi.sts.combat.catalog.CardType;
import fr.insastronaute.webapi.sts.combat.engine.effect.ResolutionStep;
import fr.insastronaute.webapi.sts.combat.engine.relic.RelicHandler;
import fr.insastronaute.webapi.sts.combat.event.CombatEvent;
import fr.insastronaute.webapi.sts.combat.model.CombatCounters;
import fr.insastronaute.webapi.sts.combat.model.CombatantState;
import fr.insastronaute.webapi.sts.combat.model.RandomState;
import fr.insastronaute.webapi.sts.combat.model.StatusInstance;
import fr.insastronaute.webapi.sts.combat.model.TimelineEntry;
import java.util.List;
import java.util.UUID;
import org.springframework.stereotype.Component;

/**
 * Logical sequence: a Power played right after a Skill draws its owner two cards.
 */
@Component
public class ScholarSequenceRelicHandler implements RelicHandler {

    @Override
    public String id() {
        return "ScholarSequenceRelic";
    }

    @Override
    public ResolutionStep onCardPlayed(
            CombatantState owner,
            CardDefinition card,
            CombatCounters counters,
            List<CombatantState> combatants,
            List<TimelineEntry> timeline,
            RandomState random,
            UUID combatId,
            long revision,
            List<CombatEvent> events
    ) {
        if (card.type() != CardType.POWER || counters.lastCardTypePlayed() != CardType.SKILL) {
            return new ResolutionStep(combatants, timeline, events, random);
        }
        return RelicActions.draw(
                owner, 2, combatants, timeline, random, combatId, revision, events);
    }
}
